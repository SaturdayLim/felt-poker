#!/usr/bin/env node
// Generates every token file from tokens/tokens.json.
//   node tools/build-tokens.js
// Writes: css/tokens.css, css/skin-codigo.css, tokens/tailwind.preset.js, tokens/tailwind-theme.css
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const T = JSON.parse(fs.readFileSync(path.join(root, 'tokens', 'tokens.json'), 'utf8'));
const header = `/* Saturday Signature v${T.meta.version}. Generated by tools/build-tokens.js from tokens/tokens.json. Do not edit by hand. */\n`;

const hexToRgba = (hex, a) => {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
  return `rgba(${r},${g},${b},${a})`;
};

// Colour block for one skin + mode. Mesh colours get their opacity baked in.
const colourVars = (c, indent = '  ') => {
  const out = [];
  for (const [k, v] of Object.entries(c)) {
    if (k === 'mesh-opacity') continue;
    const val = /^mesh-\d$/.test(k) ? hexToRgba(v, c['mesh-opacity']) : v;
    out.push(`${indent}--sat-${k}: ${val};`);
  }
  return out.join('\n');
};
const fontVars = (f, indent = '  ') =>
  Object.entries(f).map(([k, v]) => `${indent}--sat-font-${k}: ${v};`).join('\n');

// Every skin must define the same colour keys, or a skin would leak the other skin's values.
const baseKeys = Object.keys(T.skins.saturday.light).sort().join();
for (const [name, s] of Object.entries(T.skins)) {
  for (const mode of ['light', 'dark']) {
    if (Object.keys(s[mode]).sort().join() !== baseKeys) {
      throw new Error(`skins.${name}.${mode} keys differ from skins.saturday.light`);
    }
  }
}

const statics = [];
for (const [k, v] of Object.entries(T.type.size)) statics.push(`  --sat-fs-${k}: ${v};`);
for (const [k, v] of Object.entries(T.type.leading)) statics.push(`  --sat-lh-${k}: ${v};`);
for (const [k, v] of Object.entries(T.type.tracking)) statics.push(`  --sat-track-${k}: ${v};`);
for (const [k, v] of Object.entries(T.space)) statics.push(`  --sat-space-${k}: ${v};`);
for (const [k, v] of Object.entries(T.radius)) statics.push(`  --sat-radius-${k}: ${v};`);
for (const [k, v] of Object.entries(T.layout)) statics.push(`  --sat-${k}: ${v};`);
for (const [k, v] of Object.entries(T.motion)) statics.push(`  --sat-${k.startsWith('ease') ? k : 'dur-' + k}: ${v};`);
statics.push(`  --sat-blur: ${T.glass.blur};`, `  --sat-saturate: ${T.glass.saturate};`);

const sat = T.skins.saturday;
const tokensCss = `${header}
:root {
  color-scheme: light;
${statics.join('\n')}
${fontVars(sat.fonts)}
${colourVars(sat.light)}
}

/* Touch screens: 16px body (stops iOS zoom on inputs) and lighter blur for scroll performance. */
@media (pointer: coarse) {
  :root {
    --sat-fs-body: ${T.type.size['body-touch']};
    --sat-blur: ${T.glass['blur-touch']};
  }
}

@media (prefers-reduced-motion: reduce) {
  :root { --sat-dur-fast: 0ms; --sat-dur-base: 0ms; --sat-dur-slow: 0ms; }
}

/* Dark: follows the OS unless the page pins data-theme="light". */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colourVars(sat.dark, '    ')}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${colourVars(sat.dark)}
}
`;
fs.writeFileSync(path.join(root, 'css', 'tokens.css'), tokensCss);

for (const [name, s] of Object.entries(T.skins)) {
  if (name === 'saturday') continue;
  const sel = `:root[data-skin="${name}"]`;
  const css = `${header}/* Skin: ${name}. Load after tokens.css and set <html data-skin="${name}">. */

${sel} {
${fontVars(s.fonts)}
${colourVars(s.light)}
}
@media (prefers-color-scheme: dark) {
  ${sel}:not([data-theme="light"]) {
${colourVars(s.dark, '    ')}
  }
}
${sel}[data-theme="dark"] {
${colourVars(s.dark)}
}
`;
  fs.writeFileSync(path.join(root, 'css', `skin-${name}.css`), css);
}

// Tailwind: every colour points at the CSS variable, so theme and skin switching keep working.
const colourKeys = Object.keys(sat.light).filter(k => !['mesh-opacity', 'shadow', 'shadow-lg', 'theme-color'].includes(k));
const twColours = Object.fromEntries(colourKeys.map(k => [k, `var(--sat-${k})`]));
const preset = `// Saturday Signature v${T.meta.version}. Tailwind v3 preset. Generated, do not edit.
// tailwind.config.js:  module.exports = { presets: [require('./saturday/tokens/tailwind.preset.js')], ... }
module.exports = {
  theme: {
    extend: {
      colors: { sat: ${JSON.stringify(twColours, null, 8).replace(/\n}/, '\n      }')} },
      fontFamily: {
        display: ['var(--sat-font-display)'],
        sans: ['var(--sat-font-ui)'],
        mono: ['var(--sat-font-mono)'],
      },
      fontSize: ${JSON.stringify(Object.fromEntries(Object.keys(T.type.size).filter(k => k !== 'body-touch').map(k => ['sat-' + k, `var(--sat-fs-${k})`])), null, 8).replace(/\n}/, '\n      }')},
      borderRadius: ${JSON.stringify(Object.fromEntries(Object.keys(T.radius).map(k => ['sat-' + k, `var(--sat-radius-${k})`])), null, 8).replace(/\n}/, '\n      }')},
      boxShadow: { sat: 'var(--sat-shadow)', 'sat-lg': 'var(--sat-shadow-lg)' },
      screens: ${JSON.stringify(T.breakpoints)},
    },
  },
};
`;
fs.writeFileSync(path.join(root, 'tokens', 'tailwind.preset.js'), preset);

const v4 = `/* Saturday Signature v${T.meta.version}. Tailwind v4 theme. Generated, do not edit.
   In your main CSS:
     @import "tailwindcss";
     @import "../saturday/css/tokens.css";
     @import "../saturday/tokens/tailwind-theme.css";
   Then use classes such as bg-sat-glass-1, text-sat-muted, font-display, rounded-sat-lg. */
@theme inline {
${colourKeys.map(k => `  --color-sat-${k}: var(--sat-${k});`).join('\n')}
  --font-display: var(--sat-font-display);
  --font-sans: var(--sat-font-ui);
  --font-mono: var(--sat-font-mono);
${Object.keys(T.radius).map(k => `  --radius-sat-${k}: var(--sat-radius-${k});`).join('\n')}
  --shadow-sat: var(--sat-shadow);
  --shadow-sat-lg: var(--sat-shadow-lg);
${Object.entries(T.breakpoints).map(([k, v]) => `  --breakpoint-${k}: ${v};`).join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'tokens', 'tailwind-theme.css'), v4);

console.log('Built css/tokens.css, css/skin-*.css, tokens/tailwind.preset.js, tokens/tailwind-theme.css');
